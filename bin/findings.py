#!/usr/bin/env python3
"""Write results/FINDINGS.md with an LLM from DESIGN.md, claims.md and summary.md, then validate it
(DESIGN.md, Report / FINDINGS.md). Never replaces the previous file unless the draft passes every check."""
import argparse, json, os, re, subprocess, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from common import *

MODEL = "claude-fable-5-1"
SECTIONS = ["## Summary",
            "## Question 1: can a skill branch on model identity or capability?",
            "## Question 2: is a single skill file portable?",
            "## Question 3: what does a model-conditional skill cost?",
            "## Caveats", "## Guidance for skill authors"]
MODEL_WORDS = ("opus", "sonnet", "haiku", "luna", "gpt-5", "claude models", "claude model", "pair", "subject", "model")
WORD_TARGET, WORD_LIMIT = 1300, 1800

INSTRUCTIONS = """You are writing results/FINDINGS.md for the experiment described in DESIGN.md below, for a human
reader who has not seen the tables. Read DESIGN.md, especially its Goal (the three questions) and its
Report section, then claims.md (checked verdicts, each with its numbers, evidence kind, and sometimes a
table or transcript exhibits) and summary.md (tables).

Structure, exactly these headings:

```
# Findings

generated by: {model}
fingerprint: {fingerprint}
valid runs: {runs}

## Summary
## Question 1: can a skill branch on model identity or capability?
## Question 2: is a single skill file portable?
## Question 3: what does a model-conditional skill cost?
## Caveats
## Guidance for skill authors
```

How to write it:
- Summary: three short paragraphs, one answer per question, no numbers. Define the shorthand here:
  "the Claude pair" for Opus, Sonnet and Haiku in Claude Code and "the Codex pair" for Codex with
  gpt-5.6-luna, then use the shorthand everywhere below.
- Each question section opens with its answer in one or two sentences, then the evidence. Use `###`
  subheadings inside a section when it covers several topics (for example identity, tier, capability,
  loading under Question 1).
- Caveats and Guidance are bullet lists. Each bullet starts with a bold lead ("- **Tier: do not use.**").
  Guidance has one bullet per kind of branch condition (vendor, harness, exact version, tier, capability
  from knowledge, capability from the session's tools) and one per delivery (native, pointer, inline),
  each saying use, do not use, or use with a stated caveat, derived only from the cited claims.
- Citations: every paragraph, every bullet and every table ends with one citation line of its own, in
  italics, listing the claim ids it rests on as links to claims.md, e.g.
  `*Claims: [tier-codex-incorrect](claims.md#tier-codex-incorrect), [guidance-skipped-by-codex](claims.md#guidance-skipped-by-codex)*`
  Cite only claims whose status in claims.md is "holds". Put nothing else in that line, and no
  citations anywhere else in the prose.
- Numbers: use only numbers that appear in claims.md or summary.md, written the same way ("0 of 48",
  "2.5x"). No arithmetic of your own. Give a rate's count the first time it appears in a section, not
  every time; after that, "every", "never" or "all" is fine when the claim says so. The Summary and the
  opening answers carry no numbers (model names such as gpt-5.6-luna do not count as numbers).
- You may use at most one small table per question section, for the cost comparisons in Question 3
  especially; copy the cells from the claim's table.
- Quote a transcript exhibit from claims.md, verbatim and in quotation marks, where it makes a finding
  concrete (for example how Codex arrived at its tier). Quote only text that appears in claims.md.
- Never attribute a result to a harness alone: "the Claude pair", "the Codex pair", "Opus in Claude
  Code", never "Claude Code does X" or "Codex does X" as if the harness caused it. Harness and model are
  confounded.
- Say how a claim is known where it matters (observed, inferred, assumed, as given in claims.md), and
  where a branch prescribes what the model does anyway (the baseline claims), say so instead of
  crediting the branch.
- Length: about {target} words, at most {limit}. Plain, direct prose. Reply with the Markdown file only.
"""


def call_model(prompt):
    env = {k: v for k, v in os.environ.items() if not k.startswith("CLAUDE")}
    cmd = ["claude", "-p", "--model", MODEL, "--output-format", "json", "--tools", "",
           "--no-session-persistence", "--max-turns", "1"]
    proc = subprocess.run(cmd, input=prompt, cwd=ROOT, capture_output=True, text=True, env=env, timeout=600)
    res = json.loads(proc.stdout)
    text = res.get("result") or ""
    text = re.sub(r"^```(?:markdown)?\s*\n|\n```\s*$", "", text.strip())
    return text, res.get("total_cost_usd")


MODEL_ID = re.compile(r"\b(?:gpt|claude)-[a-z0-9.]+(?:-[a-z0-9]+)*\b")  # gpt-5.6-luna, claude-haiku-4-5-20251001


def numerals(text):
    return set(re.findall(r"\d+(?:\.\d+)?", MODEL_ID.sub(" ", text)))


CITE_LINE = re.compile(r"^\*Claims?:\s*(.*)\*\s*$", re.M)


def blocks(body):
    """Paragraphs, with each bullet and each table as its own block; headings dropped."""
    out, cur = [], []
    for line in body.splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            if cur: out.append("\n".join(cur)); cur = []
            continue
        if s.startswith("- ") or s.startswith("* "):
            if cur: out.append("\n".join(cur)); cur = []
            cur = [line]
            continue
        if s.startswith("|") and cur and not cur[-1].strip().startswith("|") and not cur[-1].strip().startswith("*Claims"):
            out.append("\n".join(cur)); cur = []
        cur.append(line)
    if cur: out.append("\n".join(cur))
    merged = []
    for b in out:  # a citation line left on its own after a blank line belongs to the block before it
        if CITE_LINE.fullmatch(b.strip()) and merged and not CITE_LINE.search(merged[-1]):
            merged[-1] += "\n" + b
        else:
            merged.append(b)
    return merged



CITE_ID = re.compile(r"\[([a-z0-9-]+)\]\(claims\.md#([a-z0-9-]+)\)|(?<![\[(#/-])\b([a-z][a-z0-9]*(?:-[a-z0-9]+)+)\b")


def cited_ids(block):
    m = CITE_LINE.search(block)
    if not m:
        return None
    ids = []
    for a, b, c in CITE_ID.findall(m.group(1)):
        ids.append(a or c)
    return ids


def validate(draft, claims_md, summary_md, fingerprint, n_runs):
    errors = []
    by_id = {m.group(1): m.group(2) == "holds"
             for m in re.finditer(r"^### `([a-z0-9-]+)` — (holds|FAILS)", claims_md, re.M)}
    exhibits = " ".join(re.findall(r"^- exhibit `[^`]+`: (.*)$", claims_md, re.M))
    exhibits = " ".join(exhibits.split()).lower()
    head, _, body = draft.partition(SECTIONS[0])
    if not body:
        errors.append(f"missing section: {SECTIONS[0]}"); body = draft
    for sec in SECTIONS:
        if sec not in draft:
            errors.append(f"missing section: {sec}")
    for want in (f"fingerprint: {fingerprint}", f"generated by: {MODEL}", f"valid runs: {n_runs}"):
        if want not in head:
            errors.append(f"header must contain '{want}'")
    allowed = numerals(claims_md) | numerals(summary_md)
    for n in sorted(numerals(re.sub(CITE_LINE, "", body)) - allowed):
        errors.append(f"number {n} appears in the body but not in claims.md or summary.md")
    summary = body.split(SECTIONS[1])[0]
    if numerals(re.sub(CITE_LINE, "", summary)):
        errors.append("the Summary must not contain numbers")
    for b in blocks(body):
        head80 = " ".join(re.sub(CITE_LINE, "", b).split())[:80]
        ids = cited_ids(b)
        if ids is None:
            errors.append(f"block has no citation line (*Claims: ...*): \"{head80}...\"")
            continue
        if not ids:
            errors.append(f"citation line names no claim: \"{head80}...\"")
        for cid in ids:
            if cid not in by_id:
                errors.append(f"unknown claim id `{cid}` cited in: \"{head80}...\"")
            elif not by_id[cid]:
                errors.append(f"claim `{cid}` fails and cannot be cited as support in: \"{head80}...\"")
        if re.search(r"\[claim:", b):
            errors.append(f"inline [claim: ...] citation; use the trailing *Claims:* line only: \"{head80}...\"")
    prose = re.sub(CITE_LINE, "", "\n\n".join(blocks(body)))
    for sent in re.split(r"(?<=[.!?])\s+", " ".join(prose.split())):
        low = sent.lower()
        if ("claude code" in low or "codex" in low) and not any(w in low for w in MODEL_WORDS):
            errors.append(f"names a harness without its model: \"{sent[:120]}\"")
    quoted = re.findall(r"“([^”]+)”", prose)  # curly quotes pair unambiguously
    for para in prose.split("\n"):  # straight quotes: pair them in order within a line
        parts = para.split('"')
        quoted += parts[1::2] if len(parts) % 2 == 1 else []
    for q in quoted:
        if len(q) >= 40 and " ".join(q.split()).lower() not in exhibits:
            errors.append(f"quoted text is not an exhibit in claims.md: \"{q[:80]}...\"")
    words = len(prose.split())
    if words > WORD_LIMIT:
        errors.append(f"too long: {words} words, limit {WORD_LIMIT}")
    return list(dict.fromkeys(errors))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--attempts", type=int, default=3)
    ap.add_argument("--dry-run", action="store_true", help="validate the existing FINDINGS.md only")
    args = ap.parse_args()
    design = (ROOT / "DESIGN.md").read_text()
    claims_md = (RESULTS / "claims.md").read_text()
    summary_md = (RESULTS / "summary.md").read_text()
    fp = re.search(r"fingerprint: `([0-9a-f]{16})`", claims_md).group(1)
    n_runs = int(re.search(r"valid runs: (\d+)", claims_md).group(1))
    if args.dry_run:
        errs = validate((RESULTS / "FINDINGS.md").read_text(), claims_md, summary_md, fp, n_runs)
        print("\n".join(errs) or "FINDINGS.md passes validation")
        sys.exit(1 if errs else 0)
    instructions = INSTRUCTIONS.format(model=MODEL, fingerprint=fp, runs=n_runs, target=WORD_TARGET, limit=WORD_LIMIT)
    prompt = f"{instructions}\n\n===== DESIGN.md =====\n{design}\n\n===== claims.md =====\n{claims_md}\n\n===== summary.md =====\n{summary_md}\n"
    total, errors, draft = 0.0, [], ""
    for attempt in range(1, args.attempts + 1):
        p = prompt if not errors else prompt + "\n\n===== Your previous draft =====\n" + draft + \
            "\n\n===== Validation errors to fix (return the whole corrected file) =====\n- " + "\n- ".join(errors) + "\n"
        draft, cost = call_model(p)
        total += cost or 0
        errors = validate(draft, claims_md, summary_md, fp, n_runs)
        print(f"attempt {attempt}: {len(errors)} validation errors, USD {cost or 0:.2f}", file=sys.stderr)
        for e in errors[:20]:
            print("  -", e, file=sys.stderr)
        if not errors:
            (RESULTS / "FINDINGS.md").write_text(draft.rstrip() + "\n")
            print(f"wrote results/FINDINGS.md ({len(draft.split())} words, USD {total:.2f})", file=sys.stderr)
            return
    (RESULTS / "FINDINGS.rejected.md").write_text(draft.rstrip() + "\n\n<!-- rejected: " + "; ".join(errors) + " -->\n")
    print(f"no valid draft after {args.attempts} attempts; FINDINGS.md left unchanged, last draft in "
          f"results/FINDINGS.rejected.md (USD {total:.2f})", file=sys.stderr)
    sys.exit(1)


if __name__ == "__main__":
    main()
